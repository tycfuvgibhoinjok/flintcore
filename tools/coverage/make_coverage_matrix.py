#!/usr/bin/env python3
"""Builds the coverage matrix of the reference.

The matrix answers the question "is the core a copy of everything of the
reference": for every class of the reference it shows where the port
implements it and how the implementation is checked.

The status of a class is taken from the plan: the item of the plan that
mentions the class decides the status, and the classes that the plan does
not mention at all are the holes of the audit.

    python3 tools/coverage/make_coverage_matrix.py [--plan PATH] [--out PATH]
"""

import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
REFERENCE = ROOT / ".references/Project-Poseidon/src/main/java/net/minecraft/server"
PORT = ROOT / "src"
DEFAULT_PLAN = pathlib.Path("/home/user/.opencode/plan/vanilla-core-gap-analysis.md")
DEFAULT_OUT = ROOT / "docs/coverage-matrix.md"

# The statuses of the items of the plan (the order is the order of the
# legend of the plan).
STATUSES = [
    "ИСПРАВЛЕНО",
    "СВЕРЕНО",
    "ОСОЗНАННОЕ ОТКЛОНЕНИЕ",
    "НЕ ПРИМЕНИМО",
    "ОШИБКА ПЛАНА",
    "ОТКРЫТ",
]

ITEM_HEADER = re.compile(
    r"^\*\*([A-Z]-\d+) (.+?)\*\* — [HML] — ([A-ZА-ЯЁ ]+)$", re.MULTILINE
)


def reference_classes() -> list[str]:
    return sorted(path.stem for path in REFERENCE.glob("*.java"))


def plan_items(text: str) -> list[tuple[str, str, str, str]]:
    """The items of the plan: the id, the title, the status and the text."""
    items = []
    matches = list(ITEM_HEADER.finditer(text))
    for index, match in enumerate(matches):
        start = match.end()
        end = matches[index + 1].start() if index + 1 < len(matches) else len(text)
        items.append((match.group(1), match.group(2), match.group(3).strip(), text[start:end]))
    return items


PREFIXES = (
    "Block",
    "Entity",
    "Packet",
    "Item",
    "TileEntity",
    "Chunk",
    "Container",
    "Biome",
    "ChunkProvider",
    "World",
)


def snake_names(name: str) -> list[str]:
    """The names of the port that can belong to a class of the reference."""
    candidates = [name]
    for prefix in PREFIXES:
        if name.startswith(prefix) and len(name) > len(prefix):
            candidates.append(name[len(prefix):])
    names = []
    for candidate in candidates:
        snake = re.sub(r"(?<!^)(?=[A-Z])", "_", candidate).upper()
        names.append(snake)
        names.append(snake.replace("_", ""))
    return names


def port_references() -> dict[str, list[str]]:
    """The files of the port that mention a name."""
    references: dict[str, list[str]] = {}
    files = sorted(PORT.rglob("*.rs"))
    texts = {path: path.read_text(encoding="utf-8", errors="replace") for path in files}
    for name in reference_classes():
        hits = []
        for snake in snake_names(name):
            if len(snake) < 3:
                continue
            for path, text in texts.items():
                if snake in text:
                    hits.append(str(path.relative_to(ROOT)))
            if hits:
                break
        if hits:
            references[name] = sorted(set(hits))
    return references


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--plan", type=pathlib.Path, default=DEFAULT_PLAN)
    parser.add_argument("--out", type=pathlib.Path, default=DEFAULT_OUT)
    args = parser.parse_args()

    if not args.plan.exists():
        print(f"the plan is missing: {args.plan}", file=sys.stderr)
        return 1

    plan_text = args.plan.read_text(encoding="utf-8")
    items = plan_items(plan_text)
    references = port_references()

    rows = []
    holes = []
    for name in reference_classes():
        item_id = ""
        status = ""
        for candidate_id, _title, candidate_status, body in items:
            if name in body:
                item_id = candidate_id
                status = candidate_status
                break
        files = references.get(name, [])
        rows.append((name, item_id, status, files))
        if not item_id and not files:
            holes.append(name)

    lines = [
        "# The coverage matrix of the reference",
        "",
        "Generated by `tools/coverage/make_coverage_matrix.py` — do not edit by hand.",
        "",
        f"The reference has **{len(rows)}** classes in "
        "`net.minecraft.server`.",
        "",
        "| Класс | Пункт плана | Статус | Файлы порта |",
        "|---|---|---|---|",
    ]
    for name, item_id, status, files in rows:
        files_text = ", ".join(f"`{file}`" for file in files[:3]) or "—"
        lines.append(
            f"| `{name}` | {item_id or '—'} | {status or '—'} | {files_text} |"
        )
    lines.append("")
    lines.append(
        f"**Не классифицированы:** {len(holes)} — класс, который не упомянут "
        "ни в плане, ни в порту (по имени)."
    )
    if holes:
        lines.append("")
        for name in holes:
            lines.append(f"* `{name}`")
    lines.append("")

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines), encoding="utf-8")

    accounted = sum(1 for row in rows if row[1] or row[3])
    print(
        f"{len(rows)} classes, {accounted} are in the plan or in the port, "
        f"{len(holes)} are not classified -> {args.out}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
